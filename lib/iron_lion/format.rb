# frozen_string_literal: true

module IronLion
  # A complete, validated layout of 122 payload bits. Build one with
  # IronLion.configure or IronLion.define rather than directly.
  #
  # Every format leads with a time field, so ids always sort by creation.
  # Bits left over after the declared fields become a trailing `random`.
  class Format
    attr_reader :fields, :clock

    def initialize(declarations)
      offset = 0

      @fields = Declaration.arrange(declarations).map do |proto|
        field = Field.new(
          name: proto.name,
          kind: proto.kind,
          bits: proto.bits,
          offset: offset,
          options: proto.options
        )

        offset += proto.bits
        field
      end.freeze

      @by_name = @fields.to_h { [_1.name, _1] }.freeze
      @time = @fields.first
      @counter = @fields.find { _1.kind == :counter }
      @clock = Clock.new(@counter&.max)
      @id_class = build_id_class

      freeze
    end

    def field_names = @by_name.keys

    def generate(record = nil, **values)
      reject_unknown! values
      millisecond, sequence = timestamp(values)

      payload = @fields.sum do |field|
        field.place(raw_value(field, record, values, millisecond, sequence))
      end

      @id_class.new(self, Layout.to_uuid(payload))
    end

    def parse(input)
      uuid = case input
             when Id then input.to_i
             when Integer then input
             else Layout.from_string(input.to_s)
             end

      @id_class.new(self, uuid)
    end

    # Decodes one field from a payload.
    def read(payload, name)
      field = @by_name.fetch(name) do
        raise KeyError,
              "this format has no #{name} field (it has #{field_names.join(', ')})"
      end

      decode field, field.extract(payload)
    end

    # The language-neutral description other back ends (SQL, Rust) consume.
    def to_h
      {
        version: 8,
        payload_bits: Layout::PAYLOAD_BITS,
        fields: @fields.map(&:to_h)
      }
    end

    def inspect
      "#<IronLion::Format #{@fields.map { "#{_1.name}:#{_1.bits}" }.join(' ')}>"
    end

    private

    def reject_unknown!(values)
      unknown = values.keys - field_names
      return if unknown.empty?

      raise ArgumentError,
            "unknown field #{unknown.map(&:inspect).join(', ')}; " \
            "this format has #{field_names.join(', ')}"
    end

    def timestamp(values)
      given = values[@time.name]
      return @clock.tick unless given

      millisecond = to_millisecond(given)
      [millisecond, @counter && SecureRandom.random_number(@counter.max + 1)]
    end

    def to_millisecond(time)
      return time if time.is_a?(Integer)
      return (time.to_time.to_r * 1000).floor if time.respond_to?(:to_time)

      raise InvalidValueError, "#{@time.name} must be a Time or Unix milliseconds, not #{time.inspect}"
    end

    def raw_value(field, record, values, millisecond, sequence)
      case field.kind
      when :time then elapsed(field, millisecond)
      when :counter then generated!(field, values) || sequence
      when :random then generated!(field, values) || SecureRandom.random_number(field.max + 1)
      else Resolver.resolve(field, record, values)
      end
    end

    def generated!(field, values)
      return unless values.key?(field.name)

      raise ArgumentError, "#{field.name} is generated by IronLion and cannot be supplied"
    end

    def elapsed(field, millisecond)
      raw = millisecond - field.options[:epoch_ms]
      return raw if raw.between?(0, field.max)

      raise OverflowError,
            "#{Time.at(Rational(millisecond, 1000)).utc} is outside the #{field.bits}-bit range of #{field.name}"
    end

    def decode(field, raw)
      case field.kind
      when :time
        millisecond = field.options[:epoch_ms] + raw
        Time.at(millisecond / 1000, millisecond % 1000, :millisecond, in: "UTC")
      when :value
        field.model? ? field.options[:table].model_for(raw) : raw
      when :text then Base36.decode(raw)
      else raw
      end
    end

    def build_id_class
      names = field_names

      Class.new(Id) do
        names.each { |name| define_method(name) { self[name] } }
      end
    end
  end
end
